// Writes src/constants/blogIndex.js: every article WITHOUT its body.
//
// The SEO table (src/constants/seo.js) needs each post's slug, title, excerpt,
// date and image on every page — it maps URLs to routes and writes the head.
// Importing src/constants/blog.js for that put the full text of every article
// into the first JavaScript file of every visitor. This index is the same list
// minus `body` (reading time and word count already computed), so the bodies
// stay in the blog page's own chunk.
//
// Runs before `vite build` (package.json). tests/blog-index.test.mjs fails if
// the committed file is stale, so `vite dev` never serves an outdated one.
//
//   node scripts/blog-index.mjs

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export async function buildBlogIndex() {
  const { POSTS } = await import(pathToFileURL(path.join(root, "src/constants/blog.js")).href);
  const index = POSTS.map(({ body, ...meta }) => meta); // eslint-disable-line no-unused-vars
  return `// GENERATED by scripts/blog-index.mjs from src/constants/blog.js — do not edit.
// Every article without its body, newest first: what the SEO table and the
// routes need on every page. The bodies live in the blog page's chunk.
export const POST_INDEX = ${JSON.stringify(index, null, 2)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, "src/constants/blogIndex.js");
  await fs.writeFile(out, await buildBlogIndex(), "utf8");
  console.log(`blog-index: ${path.relative(root, out)} written`);
}
